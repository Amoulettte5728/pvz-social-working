import re,sys
# id: (price/sun, bulletId, bulletAtt, damageType)   -1 = no bullet
S={1:(25,0,0,0),2:(50,0,0,0),3:(150,0,0,0),4:(25,-1,0,0),5:(75,-1,0,0),6:(100,-1,0,0),7:(75,-1,0,0),
   8:(175,-1,0,0),9:(50,-1,0,0),10:(125,-1,0,0),11:(125,-1,0,0),12:(100,1,20,1),13:(0,4,20,1),
   14:(75,5,20,2),15:(25,6,20,1),16:(175,2,20,3),17:(150,-1,0,5),18:(25,-1,0,5),19:(0,4,20,1),
   20:(150,-1,0,1),21:(100,-1,0,1),22:(50,-1,0,1),23:(25,-1,0,1),24:(200,1,20,1),25:(125,-1,0,5),
   27:(125,7,20,1),33:(100,-1,0,0),41:(300,13,80,2),42:(250,1,20,1),43:(150,-1,20,2),45:(200,14,80,11),
   57:(175,-1,0,1),71:(125,-1,0,5),72:(125,18,20,11),73:(125,3,40,6),74:(200,-1,0,0),75:(100,-1,0,0)}
p=sys.argv[1]; s=open(p,encoding='utf-8',newline='').read(); n=0
def rep(m):
    global n
    t=m.group(0); pid=int(re.search(r'<plant id="(\d+)"',t).group(1))
    if pid not in S or 'bulletId=' in t: return t
    pr,b,ba,dt=S[pid]; n+=1
    t=re.sub(r' price="\d+"',f' price="{pr}"',t)
    return t[:-1]+f' bulletId="{b}" bulletAtt="{ba}" damageType="{dt}">'
s=re.sub(r'<plant id="\d+"[^>]*>',rep,s)
open(p,'w',encoding='utf-8',newline='').write(s); print('updated',n)
